import mongoose from 'mongoose';
/*
 * Deterministic DEMO data. Every value produced here is synthetic, stored with origin "seed" and
 * sourceKey "demo-fixture", and labelled "Demo data" in the UI. It exists so the full product works
 * offline/without API keys. It is never presented as a measurement of the real place.
 */
import { Metric } from '../models/Metric.js';
import { Poi } from '../models/Poi.js';
import { HistoricalMetric } from '../models/HistoricalMetric.js';
import { Source } from '../models/Source.js';
import { poiMetrics } from './normalize.js';
import { SEARCH_RADIUS_M } from './adapters/overpass.js';

export const DEMO_SOURCE = {
  key: 'demo-fixture', provider: 'HomeIntel', name: 'HomeIntel synthetic demo fixture (not real measurements)',
  url: null, license: 'N/A — synthetic', attribution: 'Synthetic demo data generated by HomeIntel', isDemo: true,
};

function hash(s) { let h = 2166136261; for (const c of s) { h ^= c.charCodeAt(0); h = Math.imul(h, 16777619); } return h >>> 0; }
export function prng(seed) { let a = hash(seed); return () => { a += 0x6d2b79f5; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }

// Per-type [min,max] synthetic counts within the 3 km search area.
const TYPE_RANGES = { school: [6, 40], college: [0, 8], hospital: [1, 9], clinic: [4, 30], pharmacy: [4, 30], police: [0, 3], fire_station: [0, 2], rail_station: [0, 3], bus_stop: [8, 70], grocery: [6, 60], bank: [4, 40], park: [1, 18], construction: [0, 10] };
const LABEL = { school: 'School', college: 'College', hospital: 'Hospital', clinic: 'Clinic', pharmacy: 'Pharmacy', police: 'Police station', fire_station: 'Fire station', rail_station: 'Station', bus_stop: 'Bus stop', grocery: 'Grocery', bank: 'Bank', park: 'Park', construction: 'Construction site' };

export function generateDemo(nb, now = new Date()) {
  const rnd = prng(`homeintel-demo:${nb.slug}`);
  const density = 0.35 + rnd() * 0.65;
  const pois = [];
  for (const [type, [lo, hi]] of Object.entries(TYPE_RANGES)) {
    const n = Math.round(lo + (hi - lo) * density * (0.6 + rnd() * 0.4));
    for (let i = 0; i < n; i++) {
      const d = Math.sqrt(rnd()) * SEARCH_RADIUS_M; const th = rnd() * 2 * Math.PI;
      const lat = nb.lat + (d * Math.cos(th)) / 111_320; const lng = nb.lng + (d * Math.sin(th)) / (111_320 * Math.cos((nb.lat * Math.PI) / 180));
      pois.push({ ref: `demo:${nb.slug}:${type}:${i}`, type, name: `Demo ${LABEL[type].toLowerCase()} ${i + 1}`, lat, lng, distanceM: Math.round(d) });
    }
  }
  pois.sort((a, b) => a.distanceM - b.distanceM);
  const meta = { origin: 'seed', sourceKey: 'demo-fixture' };
  const metrics = poiMetrics(pois, SEARCH_RADIUS_M, meta).map((m) => ({ ...m, scope: `${m.scope.replace(' (as mapped in OpenStreetMap)', '')} — synthetic demo value` }));
  const pm = Math.round((18 + rnd() * 90) * 10) / 10;
  metrics.push({ key: 'pm25', category: 'environment', label: 'PM2.5 (latest)', value: pm, unit: 'µg/m³', granularity: 'station', scope: 'Demo monitoring station — synthetic demo value', distanceKm: Math.round((1 + rnd() * 8) * 10) / 10, observedAt: now, confidence: 0.5, details: { station: 'Demo station' }, ...meta });
  metrics.push({ key: 'crime_demo', category: 'safety', label: 'Recorded IPC crime rate', value: Math.round(150 + rnd() * 500), unit: 'per 100k people', granularity: 'city', scope: `${nb.city} (city-level) — synthetic demo value, not NCRB data`, confidence: 0.4, details: { beatsShareOfAreas: Math.round(rnd() * 1000) / 1000, areasInTable: 19, valueKind: 'rate_per_lakh' }, ...meta });
  const history = [];
  for (let i = 23; i >= 0; i--) {
    const d = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() - i, 1));
    const seasonal = 1 + 0.45 * Math.cos(((d.getUTCMonth() - 11) / 12) * 2 * Math.PI);  // synthetic winter peak shape
    history.push({ observedAt: d, value: Math.round(pm * seasonal * (0.85 + rnd() * 0.3) * 10) / 10 });
  }
  return { pois, metrics, history };
}

export async function seedDemoFor(nb) {
  await Source.updateOne({ key: DEMO_SOURCE.key }, { $set: DEMO_SOURCE }, { upsert: true });
  // Never overwrite source-backed data with demo data.
  if (await Metric.exists({ neighborhoodId: nb._id, origin: mongoose.trusted({ $in: ['live', 'cached'] }) })) return { skipped: true };
  const now = new Date();
  const { pois, metrics, history } = generateDemo(nb, now);
  await Promise.all([Metric.deleteMany({ neighborhoodId: nb._id }), Poi.deleteMany({ neighborhoodId: nb._id }), HistoricalMetric.deleteMany({ neighborhoodId: nb._id })]);
  await Poi.insertMany(pois.map((p) => ({ ...p, neighborhoodId: nb._id, origin: 'seed', sourceKey: 'demo-fixture', collectedAt: now })));
  await Metric.insertMany(metrics.map((m) => ({ ...m, neighborhoodId: nb._id, collectedAt: now })));
  await HistoricalMetric.insertMany(history.map((h) => ({ ...h, neighborhoodId: nb._id, key: 'pm25', period: 'month', unit: 'µg/m³', origin: 'seed', sourceKey: 'demo-fixture', collectedAt: now })));
  return { pois: pois.length, metrics: metrics.length, history: history.length };
}
